// template: write the Switch room templates (templates/<room>.template.yaml) from the same content the
// seed command uses. They are the no-script fallback: Console → Templates → Import template.
// A template can't turn join events on or create the agent's own documents (judge-path §0.4, §0.5),
// so the seed command stays the main route; the header of each file says what to do by hand.
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { DEMOS, demoContent, roomRules } from './content.ts';

const q = (s: string) => JSON.stringify(s); // a JSON string is a valid YAML double-quoted scalar
const block = (s: string, indent: string) =>
  '|\n' + s.replace(/\s+$/, '').split('\n').map((l) => (l ? indent + l : '')).join('\n');

export function renderTemplate(demo: (typeof DEMOS)[number], root = '.'): { file: string; yaml: string } {
  const c = demoContent(demo, root);
  const instructions = `${roomRules(root)}\n\nRoom owner: {$creator} (only this person confirms decisions or rules on clashes, in the owner desk).`;
  const lines = [
    `# ${c.roomName}: Context Keeper demo room. GENERATED by \`npm run seed -- --emit-templates\` from`,
    `# prompts/room-rules.md and demo/${demo}/ — edit those, not this file.`,
    '#',
    '# The main route is the seed command (`npm run seed -- --bridge <app>`), which also does what a',
    '# template cannot. If you import this in Console (Templates → Import template) instead:',
    '#   - turn on join events for context-keeper in the room (Notify on join), or the late-joiner brief never fires;',
    '#   - documents made by a template belong to you, not the agent. That is fine for these; the agent',
    '#     creates its own "Decision log" when it starts;',
    '#   - make the owner desk yourself: a private channel with only you and context-keeper.',
    '# No kickoff: on purpose (Switch #1158: on Mattermost a kickoff card retries forever).',
    'params:',
    '  room_name:',
    '    type: string',
    `    default: ${q(c.roomName)}`,
    '    description: The room (and channel) name',
    '  bridge:',
    '    type: bridge',
    '    default: [$first]',
    '    description: The messaging app the room lives on',
    'room:',
    '  name: "{room_name}"',
    `  description: ${q(c.description)}`,
    `  instructions: ${block(instructions, '    ')}`,
    '  bridge: "{bridge}"',
    '  channel_type: channel_public',
    '  agents: [context-keeper]',
    '  users: ["{$creator}"]',
    '  docs:',
  ];
  for (const d of c.docs) {
    lines.push(`    - name: ${q(d.name)}`);
    lines.push(`      description: ${q(d.description)}`);
    lines.push(`      instructions: ${q(d.instructions)}`);
    lines.push(`      content: ${block(d.content, '        ')}`);
  }
  return { file: join(root, 'templates', `${c.roomName}.template.yaml`), yaml: lines.join('\n') + '\n' };
}

export function writeTemplates(root = '.'): string[] {
  mkdirSync(join(root, 'templates'), { recursive: true });
  return DEMOS.map((d) => {
    const { file, yaml } = renderTemplate(d, root);
    writeFileSync(file, yaml);
    return file;
  });
}
